export const importChargeKeys = Object.keys(importChargeLabels) as ImportChargeKey[];
export const importDutyKeys = Object.keys(importDutyLabels) as ImportDutyKey[];

export function createEmptyInvoiceCharges(currency = "USD", exchangeRate = "83.00") {
  return importChargeKeys.map<ImportInvoiceCharge>((key) => ({
    key,
    apply: false,
    currency,
    exchangeRate,
    rate: "",
    amount: "",
  }));
}

export function createEmptyDutyRows() {
  return importDutyKeys.map((key) => ({
    key,
    notification: "",
    serialNo: "",
    rate: "",
    amount: "",
    uom: "",
    flag: "",
    manualOverride: false,
  }));
}

