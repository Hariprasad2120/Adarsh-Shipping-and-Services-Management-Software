export function createBlankImportJobDraft(now = new Date()): ImportJobDraft {
  const timestamp = now.toISOString();

  return {
    id: "import-lab-draft",
    schemaVersion: IMPORT_JOB_STORAGE_SCHEMA_VERSION,
    movementDirection: "IMPORT",
    status: "DRAFT",
    activeTab: "be-main-details",
    createdAt: timestamp,
    updatedAt: timestamp,
    mainDetails: createEmptyMainDetails(),
    igmRecords: [],
    invoiceRecords: [],
    itemRecords: [],
    declarationRecords: [],
    supportingDocumentRecords: [],
    checklistOptions: {
      selectedJobNo: "",
      jobDate: "",
      withDeclaration: true,
      printGeneratedAt: "",
    },
    flatFileOptions: {
      selectedJobNo: "",
      jobDate: "",
      dummyJob: true,
      lastGeneratedAt: "",
      lastChecksum: "",
      lastFlatFile: "",
      lastJson: "",
      lastValidationReport: "",
      history: [],
    },
  };
}

